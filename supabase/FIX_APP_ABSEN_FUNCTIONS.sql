-- 5. Fungsi get_my_leave_balance (Untuk Saldo Cuti di app-absen)
CREATE OR REPLACE FUNCTION public.get_my_leave_balance(p_as_of date default current_date)
RETURNS TABLE(
  period_id bigint, period_kind text, period_start date, period_end date, employment_type text,
  entitlement_days numeric, carry_forward_days numeric, collective_leave_days numeric, used_days numeric,
  expired_days numeric, remaining_days numeric, status text
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT 
    coalesce(b.id, 1), 
    coalesce(b.period_kind, 'calendar_year'), 
    coalesce(b.period_start, date_trunc('year', p_as_of)::date), 
    coalesce(b.period_end, (date_trunc('year', p_as_of) + interval '1 year - 1 day')::date), 
    coalesce(b.employment_type, coalesce(u.contract_type, 'PKWTT')),
    coalesce(b.entitlement_days, 12), 
    coalesce(b.carry_forward_days, 0),
    coalesce(b.collective_leave_days, 4), 
    coalesce(b.used_days, (
      SELECT coalesce(sum(r.total_days), 0) FROM public.leave_requests r
      WHERE r.user_id::text = u.id::text AND r.status = 'approved'
        AND r.leave_type = 'annual' AND extract(year from r.start_date) = extract(year from p_as_of)
    )),
    coalesce(b.expired_days, 0),
    greatest(0, coalesce(b.entitlement_days, 12) + coalesce(b.carry_forward_days, 0) - coalesce(b.collective_leave_days, 4) - coalesce(b.used_days, (
      SELECT coalesce(sum(r.total_days), 0) FROM public.leave_requests r
      WHERE r.user_id::text = u.id::text AND r.status = 'approved'
        AND r.leave_type = 'annual' AND extract(year from r.start_date) = extract(year from p_as_of)
    ))),
    'active'
  FROM public.user_accounts u
  LEFT JOIN public.leave_balance_periods b 
    ON b.user_id = u.id AND b.status = 'active' AND b.period_start <= p_as_of AND b.period_end >= p_as_of
  WHERE u.id::text = public.current_account_id()
  ORDER BY b.period_start DESC NULLS LAST
  LIMIT 1;
$$;
GRANT EXECUTE ON FUNCTION public.get_my_leave_balance(date) TO authenticated, anon;

-- 6. Fungsi get_my_national_id (Untuk NIK di Profil)
CREATE OR REPLACE FUNCTION public.get_my_national_id() RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT coalesce(nik, 'Belum diisi') FROM public.user_accounts WHERE id::text = public.current_account_id();
$$;
GRANT EXECUTE ON FUNCTION public.get_my_national_id() TO authenticated, anon;

-- 7. Fungsi update_my_avatar (Upload Foto Profil)
CREATE OR REPLACE FUNCTION public.update_my_avatar(p_avatar_url text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_user text := public.current_account_id();
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'USER_ACCOUNT_NOT_FOUND'; END IF;
  UPDATE public.user_accounts SET avatar_url = p_avatar_url, updated_at = now() WHERE id::text = v_user;
  RETURN p_avatar_url;
END; $$;
GRANT EXECUTE ON FUNCTION public.update_my_avatar(text) TO authenticated, anon;
