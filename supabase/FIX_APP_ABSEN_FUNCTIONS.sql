-- 1. Buat Tabel leave_balance_periods jika belum ada
CREATE TABLE IF NOT EXISTS public.leave_balance_periods (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.user_accounts(id),
  period_kind text NOT NULL CHECK(period_kind IN ('calendar_year','contract')),
  period_start date NOT NULL,
  period_end date NOT NULL,
  employment_type text NOT NULL CHECK(employment_type IN ('PKWT','PKWTT')),
  entitlement_days numeric(6,2) NOT NULL DEFAULT 0,
  carry_forward_days numeric(6,2) NOT NULL DEFAULT 0,
  collective_leave_days numeric(6,2) NOT NULL DEFAULT 0,
  used_days numeric(6,2) NOT NULL DEFAULT 0,
  expired_days numeric(6,2) NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  UNIQUE(user_id, period_kind, period_start)
);
GRANT ALL ON public.leave_balance_periods TO authenticated, anon;
