create or replace function public.current_account_id() returns text
language sql stable security definer set search_path=public as $$
  select id::text from public.user_accounts where lower(email)=lower(auth.jwt()->>'email')
    and lower(status) not in ('inactive','suspended','resigned','terminated')
    and lower(employment_status) not in ('inactive','suspended','resigned','terminated') limit 1;
$$;
create or replace function public.is_hr_admin() returns boolean
language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.user_accounts where id::text=public.current_account_id()
    and (lower(role) in ('admin','super admin','super_admin','hr','hr manager','hr staff','office_management')
      or groups && array['hr','hrd','it_management','csl_admin']));
$$;

