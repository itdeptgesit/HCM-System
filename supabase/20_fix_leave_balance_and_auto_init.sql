-- ==============================================================================
-- MIGRASI PERBAIKAN: INISIALISASI SALDO CUTI & AUTO-PROVISIONING DI APPROVAL
-- Mengatasi Error: LEAVE_BALANCE_PERIOD_NOT_FOUND (Kode P0001)
-- ==============================================================================

BEGIN;

-- 1. Pastikan tabel leave_balance_periods ada
CREATE TABLE IF NOT EXISTS public.leave_balance_periods (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
  period_start date NOT NULL DEFAULT CURRENT_DATE,
  period_end date NOT NULL DEFAULT (CURRENT_DATE + interval '1 year - 1 day')::date
);

-- 2. Pastikan SEMUA kolom yang dibutuhkan ada (menghindari error 42703 jika tabel sudah pernah ada sebelumnya)
ALTER TABLE public.leave_balance_periods
  ADD COLUMN IF NOT EXISTS period_kind text NOT NULL DEFAULT 'calendar_year',
  ADD COLUMN IF NOT EXISTS employment_type text NOT NULL DEFAULT 'PKWTT',
  ADD COLUMN IF NOT EXISTS entitlement_days numeric(6,2) NOT NULL DEFAULT 12,
  ADD COLUMN IF NOT EXISTS carry_forward_days numeric(6,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS collective_leave_days numeric(6,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS used_days numeric(6,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS expired_days numeric(6,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'active',
  ADD COLUMN IF NOT EXISTS source text DEFAULT 'hr_policy',
  ADD COLUMN IF NOT EXISTS notes text,
  ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now(),
  ADD COLUMN IF NOT EXISTS updated_at timestamptz DEFAULT now();

-- Pastikan kolom remaining_days ada (mendukung generated column atau default numeric)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' 
      AND table_name = 'leave_balance_periods' 
      AND column_name = 'remaining_days'
  ) THEN
    ALTER TABLE public.leave_balance_periods 
      ADD COLUMN remaining_days numeric(6,2) GENERATED ALWAYS AS (
        GREATEST(0, entitlement_days + carry_forward_days - collective_leave_days - used_days - expired_days)
      ) STORED;
  END IF;
EXCEPTION WHEN OTHERS THEN
  BEGIN
    ALTER TABLE public.leave_balance_periods ADD COLUMN IF NOT EXISTS remaining_days numeric(6,2) DEFAULT 12;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;
END $$;

-- 3. Bersihkan data duplikat jika ada sebelum membuat indeks/constraint unik
DELETE FROM public.leave_balance_periods a
USING public.leave_balance_periods b
WHERE a.id < b.id 
  AND a.user_id = b.user_id 
  AND COALESCE(a.period_kind, 'calendar_year') = COALESCE(b.period_kind, 'calendar_year')
  AND a.period_start = b.period_start;

-- Pastikan unique index ada untuk mencegah duplikasi (user_id, period_kind, period_start)
CREATE UNIQUE INDEX IF NOT EXISTS idx_leave_balance_periods_user_kind_start 
  ON public.leave_balance_periods (user_id, period_kind, period_start);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint 
    WHERE conrelid = 'public.leave_balance_periods'::regclass 
      AND contype = 'u'
      AND conname = 'leave_balance_periods_user_period_start_key'
  ) THEN
    ALTER TABLE public.leave_balance_periods
      ADD CONSTRAINT leave_balance_periods_user_period_start_key UNIQUE USING INDEX idx_leave_balance_periods_user_kind_start;
  END IF;
EXCEPTION WHEN OTHERS THEN
  NULL;
END $$;

-- 4. Inisialisasi Saldo Cuti untuk SELURUH karyawan aktif
--    Mencakup seluruh tahun dari riwayat pengajuan cuti serta tahun 2025, 2026, dan 2027
WITH target_years AS (
  SELECT DISTINCT 
    date_trunc('year', start_date)::date AS period_start,
    (date_trunc('year', start_date) + interval '1 year - 1 day')::date AS period_end
  FROM public.leave_requests
  WHERE start_date IS NOT NULL
  UNION
  SELECT '2025-01-01'::date, '2025-12-31'::date
  UNION
  SELECT '2026-01-01'::date, '2026-12-31'::date
  UNION
  SELECT '2027-01-01'::date, '2027-12-31'::date
)
INSERT INTO public.leave_balance_periods (
  user_id,
  period_kind,
  period_start,
  period_end,
  employment_type,
  entitlement_days,
  carry_forward_days,
  collective_leave_days,
  used_days,
  expired_days,
  status,
  source
)
SELECT
  u.id AS user_id,
  'calendar_year' AS period_kind,
  y.period_start,
  y.period_end,
  CASE
    WHEN UPPER(COALESCE(u.contract_type, u.employment_type, '')) LIKE '%PKWT%' THEN 'PKWT'
    ELSE 'PKWTT'
  END AS employment_type,
  12 AS entitlement_days,
  0 AS carry_forward_days,
  CASE
    WHEN extract(year from y.period_start) = 2025 THEN 10
    WHEN extract(year from y.period_start) = 2026 THEN 8
    WHEN extract(year from y.period_start) = 2027 THEN 8
    ELSE 4
  END AS collective_leave_days,
  COALESCE(
    (
      SELECT SUM(COALESCE(r.total_days, (r.end_date - r.start_date + 1)::numeric))
      FROM public.leave_requests r
      WHERE r.user_id::text = u.id::text
        AND r.leave_type = 'annual'
        AND r.status = 'approved'
        AND r.start_date >= y.period_start 
        AND r.start_date <= y.period_end
    ),
    0
  ) AS used_days,
  0 AS expired_days,
  'active' AS status,
  'system_init' AS source
FROM public.user_accounts u
CROSS JOIN target_years y
WHERE LOWER(COALESCE(u.status, u.employment_status, 'active')) NOT IN ('inactive', 'resigned', 'terminated', 'suspended', 'nonaktif')
ON CONFLICT (user_id, period_kind, period_start) DO UPDATE
SET collective_leave_days = EXCLUDED.collective_leave_days,
    used_days = EXCLUDED.used_days,
    status = 'active',
    updated_at = now();

-- 4b. Pastikan seluruh record yang sudah ada di database ter-update collective_leave_days-nya (SKB 3 Menteri)
UPDATE public.leave_balance_periods
SET collective_leave_days = CASE
    WHEN extract(year from period_start) = 2025 THEN 10
    WHEN extract(year from period_start) = 2026 THEN 8
    WHEN extract(year from period_start) = 2027 THEN 8
    ELSE 4
  END,
  updated_at = now()
WHERE coalesce(collective_leave_days, 0) = 0;

-- Refresh used_days untuk cuti tahunan yang berstatus approved
UPDATE public.leave_balance_periods b
SET used_days = COALESCE(
  (
    SELECT SUM(COALESCE(r.total_days, (r.end_date - r.start_date + 1)::numeric))
    FROM public.leave_requests r
    WHERE r.user_id::text = b.user_id::text
      AND r.leave_type = 'annual'
      AND r.status = 'approved'
      AND r.start_date >= b.period_start
      AND r.start_date <= b.period_end
  ),
  0
),
updated_at = now();

-- Refresh remaining_days bila bukan generated column
DO $$
BEGIN
  UPDATE public.leave_balance_periods
  SET remaining_days = GREATEST(0, entitlement_days + carry_forward_days - collective_leave_days - used_days - expired_days);
EXCEPTION WHEN OTHERS THEN
  NULL;
END $$;

-- 5. Hapus signature lama yang berpotensi menimbulkan ambiguitas tipe data (uuid vs bigint)
DROP FUNCTION IF EXISTS public.review_workforce_request(text, uuid, text, text);
DROP FUNCTION IF EXISTS public.review_workforce_request_as(text, text, uuid, text, text);

-- 6. Perbarui fungsi review_workforce_request_as dengan AUTO-PROVISIONING cerdas:
--    Jika periode saldo belum ada, buatkan otomatis periode tahun berjalan secara on-the-fly
--    sehingga persetujuan email maupun dashboard TIDAK LAGI melempar exception LEAVE_BALANCE_PERIOD_NOT_FOUND (P0001).
CREATE OR REPLACE FUNCTION public.review_workforce_request_as(
  p_actor_id text, p_request_type text, p_request_id bigint, p_decision text, p_notes text default null
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_table text; v_request jsonb; v_result jsonb; v_actor public.user_accounts;
  v_level integer; v_next integer; v_assignee text; v_admin boolean; v_hr boolean; v_final boolean;
  v_status text; v_approval text; v_name text; v_balance public.leave_balance_periods; v_days numeric;
  v_stamp_column text; v_stamp_at text;
  v_user_emp_type text;
  v_req_start date;
  v_req_end date;
  v_target_user_id bigint;
BEGIN
  IF p_request_type NOT IN ('leave','overtime','reimbursement') THEN RAISE EXCEPTION 'INVALID_REQUEST_TYPE'; END IF;
  IF p_decision NOT IN ('approved','rejected','paid') THEN RAISE EXCEPTION 'INVALID_DECISION'; END IF;
  
  SELECT * INTO v_actor FROM public.user_accounts WHERE id::text=p_actor_id;
  IF v_actor.id IS NULL THEN RAISE EXCEPTION 'USER_ACCOUNT_NOT_FOUND'; END IF;
  
  v_admin := lower(coalesce(v_actor.role,'')) in ('admin','super admin','super_admin');
  v_hr := v_admin
    or lower(coalesce(v_actor.role,'')) in ('hr','hr manager','hr staff','office_management')
    or coalesce(v_actor.groups,'{}') && array['hr','hrd','it_management','csl_admin'];
  v_name := coalesce(nullif(v_actor.full_name,''),v_actor.email);
  v_table := case p_request_type when 'leave' then 'leave_requests' when 'overtime' then 'overtime_requests' else 'reimbursements' end;
  
  EXECUTE format('select to_jsonb(r) from public.%I r where id=$1 for update',v_table) INTO v_request USING p_request_id;
  IF v_request IS NULL THEN RAISE EXCEPTION 'REQUEST_NOT_FOUND'; END IF;
  IF v_request->>'user_id'=v_actor.id::text THEN RAISE EXCEPTION 'CANNOT_REVIEW_OWN_REQUEST'; END IF;

  IF p_decision='paid' THEN
    IF p_request_type<>'reimbursement' or v_request->>'status'<>'approved' or not v_hr THEN RAISE EXCEPTION 'PAYMENT_NOT_AUTHORIZED_OR_NOT_APPROVED'; END IF;
    EXECUTE format('update public.%I r set status=''paid'',updated_at=now() where id=$1 returning to_jsonb(r)',v_table) INTO v_result USING p_request_id;
    RETURN v_result;
  END IF;

  IF v_request->>'status' not like 'pending%' THEN RAISE EXCEPTION 'REQUEST_ALREADY_REVIEWED'; END IF;
  
  v_level := case v_request->>'status'
    when 'pending_line_2' then 2 when 'pending_senior' then 3 when 'pending_office' then 4
    else coalesce((v_request->>'current_approval_level')::integer,1) end;
    
  SELECT approver_id INTO v_assignee FROM public.workforce_approval_chain(v_request->>'user_id') WHERE level_number=v_level;
  IF NOT v_admin AND v_assignee IS DISTINCT FROM v_actor.id::text THEN RAISE EXCEPTION 'NOT_DESIGNATED_APPROVER'; END IF;
  
  SELECT level_number INTO v_next FROM public.workforce_approval_chain(v_request->>'user_id') WHERE level_number>v_level ORDER BY level_number LIMIT 1;
  v_final := p_decision='rejected' OR v_next IS NULL;
  v_status := case when v_final then p_decision else 'pending' end;
  v_approval := case when v_final then p_decision else 'pending_level_'||v_next end;

  -- Pengurangan ledger hanya untuk cuti tahunan pada tahap final approval
  IF p_request_type='leave' AND p_decision='approved' AND v_final AND v_request->>'leave_type'='annual' THEN
    v_req_start := (v_request->>'start_date')::date;
    v_req_end := (v_request->>'end_date')::date;
    v_days := coalesce((v_request->>'total_days')::numeric, v_req_end - v_req_start + 1);
    IF v_days <= 0 THEN v_days := 1; END IF;
    v_target_user_id := (v_request->>'user_id')::bigint;
    
    -- 1. Cari balance aktif untuk rentang tanggal pengajuan (mencakup start_date)
    SELECT * INTO v_balance FROM public.leave_balance_periods
      WHERE user_id = v_target_user_id 
        AND status = 'active'
        AND period_start <= v_req_start 
        AND period_end >= v_req_start
      ORDER BY period_start DESC LIMIT 1 FOR UPDATE;
      
    -- 2. Jika belum ditemukan, periksa apakah ada periode di tahun yang sama
    IF v_balance.id IS NULL THEN
      SELECT * INTO v_balance FROM public.leave_balance_periods
        WHERE user_id = v_target_user_id
          AND extract(year from period_start) = extract(year from v_req_start)
        ORDER BY period_start DESC LIMIT 1 FOR UPDATE;
        
      IF v_balance.id IS NOT NULL THEN
        UPDATE public.leave_balance_periods
        SET status = 'active', updated_at = now()
        WHERE id = v_balance.id
        RETURNING * INTO v_balance;
      END IF;
    END IF;

    -- 3. Jika masih belum ada, buatkan otomatis periode tahunan secara aman (Auto-Provisioning)
    IF v_balance.id IS NULL THEN
      SELECT CASE
        WHEN UPPER(COALESCE(contract_type, employment_type, '')) LIKE '%PKWT%' THEN 'PKWT'
        ELSE 'PKWTT'
      END INTO v_user_emp_type FROM public.user_accounts WHERE id = v_target_user_id;

      INSERT INTO public.leave_balance_periods (
        user_id, period_kind, period_start, period_end, employment_type,
        entitlement_days, carry_forward_days, collective_leave_days, used_days, expired_days, status, source
      ) VALUES (
        v_target_user_id,
        'calendar_year',
        date_trunc('year', v_req_start)::date,
        (date_trunc('year', v_req_start) + interval '1 year - 1 day')::date,
        COALESCE(v_user_emp_type, 'PKWTT'),
        12, 0,
        CASE
          WHEN extract(year from v_req_start) = 2025 THEN 10
          WHEN extract(year from v_req_start) = 2026 THEN 8
          WHEN extract(year from v_req_start) = 2027 THEN 8
          ELSE 4
        END,
        0, 0, 'active', 'auto_provision_approval'
      )
      ON CONFLICT (user_id, period_kind, period_start) DO UPDATE
        SET collective_leave_days = EXCLUDED.collective_leave_days,
            status = 'active',
            updated_at = now()
      RETURNING * INTO v_balance;
    END IF;

    -- 4. Safety net fallback: pastikan v_balance terisi (tidak pernah melempar LEAVE_BALANCE_PERIOD_NOT_FOUND)
    IF v_balance.id IS NULL THEN
      SELECT * INTO v_balance FROM public.leave_balance_periods
        WHERE user_id = v_target_user_id
        ORDER BY id DESC LIMIT 1;
    END IF;

    -- 5. Validasi saldo cukup
    IF v_balance.id IS NOT NULL THEN
      IF greatest(0, v_balance.entitlement_days + v_balance.carry_forward_days - v_balance.collective_leave_days - v_balance.used_days - v_balance.expired_days) < v_days THEN
        RAISE EXCEPTION 'INSUFFICIENT_LEAVE_BALANCE';
      END IF;

      -- 6. Potong saldo
      UPDATE public.leave_balance_periods
      SET used_days = used_days + v_days, updated_at = now()
      WHERE id = v_balance.id;
    END IF;
  END IF;

  v_stamp_column := case v_level when 1 then 'line1_approved_by' when 2 then 'line2_approved_by' when 3 then 'senior_approved_by' else 'office_approved_by' end;
  v_stamp_at := replace(v_stamp_column,'_by','_at');
  
  EXECUTE format('update public.%I r set status=$2,approval_status=$3,current_approval_level=$4,approved_by=$5,approved_at=now(),rejection_reason=case when $2=''rejected'' then $6 else null end,%I=$5,%I=now(),updated_at=now() where id=$1 returning to_jsonb(r)',v_table,v_stamp_column,v_stamp_at)
    INTO v_result USING p_request_id,v_status,v_approval,coalesce(v_next,v_level),v_name,nullif(trim(p_notes),'');
    
  INSERT INTO public.approval_records(request_type,request_id,level_number,approver_id,approver_name,status,notes)
    VALUES(p_request_type,p_request_id,v_level,v_actor.id::text,v_name,p_decision,p_notes);
    
  RETURN v_result;
END;
$$;

-- 7. Buat / perbarui review_workforce_request (entry point RPC yang dipanggil oleh frontend/aplikasi)
CREATE OR REPLACE FUNCTION public.review_workforce_request(
  p_request_type text, p_request_id bigint, p_decision text, p_notes text default null
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  RETURN public.review_workforce_request_as(public.current_account_id(), p_request_type, p_request_id, p_decision, p_notes);
END;
$$;

-- 7b. Perbarui fungsi prepare_workforce_email agar perhitungan sisa saldo di email selalu akurat dan sinkron dengan SKB 3 Menteri
CREATE OR REPLACE FUNCTION public.prepare_workforce_email(p_id uuid, p_lease_token uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_job public.workforce_email_outbox;
  v_request jsonb; v_recipient jsonb; v_requester jsonb;
  v_recipient_id text; v_state text; v_level integer;
  v_start date; v_days numeric; v_balance numeric;
BEGIN
  SELECT * INTO v_job FROM public.workforce_email_outbox
    WHERE id=p_id AND status='processing' AND lease_token=p_lease_token AND lease_until>now() FOR UPDATE;
  IF v_job.id IS NULL THEN RETURN NULL; END IF;

  IF NOT EXISTS(SELECT 1 FROM public.workforce_email_settings WHERE id AND enabled) THEN
    UPDATE public.workforce_email_outbox SET status='pending',attempts=greatest(0,attempts-1),lease_token=null,lease_until=null WHERE id=p_id;
    RETURN NULL;
  END IF;

  EXECUTE format('SELECT to_jsonb(r) FROM public.%I r WHERE id::text=$1',v_job.request_table)
    INTO v_request USING v_job.request_id;
  IF v_request IS NOT NULL THEN v_state := public.workforce_email_state(v_request); END IF;

  IF v_request IS NULL OR v_state IS DISTINCT FROM v_job.request_state OR EXISTS(
    SELECT 1 FROM public.workforce_email_outbox WHERE request_table=v_job.request_table
      AND request_id=v_job.request_id AND event_number>v_job.event_number
  ) THEN
    UPDATE public.workforce_email_outbox SET status='skipped',last_error='SUPERSEDED_OR_DELETED',lease_token=null,lease_until=null WHERE id=p_id;
    RETURN NULL;
  END IF;

  SELECT to_jsonb(u) INTO v_requester FROM public.user_accounts u WHERE id::text=v_request->>'user_id';
  IF v_state LIKE 'pending_level_%' THEN
    v_level := right(v_state,1)::integer;
    SELECT approver_id INTO v_recipient_id FROM public.workforce_approval_chain(v_request->>'user_id') WHERE level_number=v_level;
    IF v_recipient_id=v_request->>'user_id' THEN v_recipient_id := NULL; END IF;
  ELSE
    v_recipient_id := v_request->>'user_id';
  END IF;

  SELECT to_jsonb(u) INTO v_recipient FROM public.user_accounts u WHERE id::text=v_recipient_id;
  IF v_requester IS NULL OR v_recipient IS NULL
    OR coalesce(v_recipient->>'email','') !~ '^[A-Za-z0-9.!#$%&''*+/=?^_`{|}~-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$'
    OR lower(coalesce(v_recipient->>'status','active')) IN ('inactive','suspended','resigned','terminated','nonaktif')
    OR lower(coalesce(v_recipient->>'employment_status','active')) IN ('inactive','suspended','resigned','terminated','nonaktif') THEN
    UPDATE public.workforce_email_outbox SET status='blocked',last_error='RECIPIENT_MISSING_INVALID_OR_INACTIVE',lease_token=null,lease_until=null WHERE id=p_id;
    RETURN NULL;
  END IF;

  UPDATE public.workforce_email_outbox
    SET recipient_email=lower(v_recipient->>'email'),recipient_account_id=v_recipient->>'id'
    WHERE id=p_id;

  v_start := coalesce((v_request->>'start_date')::date,(v_request->>'attendance_date')::date,
    (v_request->>'request_date')::date,(v_request->>'date')::date);
  v_days := coalesce(nullif(v_request->>'total_days','')::numeric,
    CASE WHEN v_request->>'end_date' IS NOT NULL AND v_start IS NOT NULL
      THEN ((v_request->>'end_date')::date - v_start + 1) ELSE 1 END);

  IF v_job.request_table='leave_requests' AND v_start IS NOT NULL THEN
    BEGIN
      SELECT greatest(0, b.entitlement_days + b.carry_forward_days - b.collective_leave_days - b.used_days - b.expired_days)
        INTO v_balance FROM public.leave_balance_periods b
        WHERE b.user_id::text=v_request->>'user_id' AND b.status='active'
          AND b.period_start<=v_start AND b.period_end>=v_start
        ORDER BY b.period_start DESC LIMIT 1;

      -- Cerdas: jika collective_leave_days di record belum ada atau 0, otomatis gunakan default cuti bersama resmi
      IF v_balance IS NULL OR NOT EXISTS (
        SELECT 1 FROM public.leave_balance_periods b
        WHERE b.user_id::text=v_request->>'user_id' AND b.status='active'
          AND b.period_start<=v_start AND b.period_end>=v_start AND b.collective_leave_days > 0
      ) THEN
        DECLARE
          v_skb_collective numeric := CASE WHEN extract(year from v_start) = 2025 THEN 10 WHEN extract(year from v_start) = 2026 THEN 8 WHEN extract(year from v_start) = 2027 THEN 8 ELSE 4 END;
          v_actual_used numeric;
        BEGIN
          SELECT COALESCE(SUM(COALESCE(r.total_days, (r.end_date - r.start_date + 1)::numeric)), 0)
            INTO v_actual_used
            FROM public.leave_requests r
            WHERE r.user_id::text = v_request->>'user_id'
              AND r.leave_type = 'annual'
              AND r.status = 'approved'
              AND extract(year from r.start_date) = extract(year from v_start);
          v_balance := greatest(0, 12 - v_skb_collective - v_actual_used);
        END;
      END IF;
    EXCEPTION WHEN OTHERS THEN v_balance := NULL;
    END;
  END IF;

  RETURN jsonb_build_object(
    'id',v_job.id,'request_table',v_job.request_table,'request_id',v_job.request_id,
    'state',v_state,'level',v_level,'recipient_email',lower(v_recipient->>'email'),
    'recipient_name',v_recipient->>'full_name','requester_name',v_requester->>'full_name',
    'recipient_id',v_recipient->>'id',
    'start_date',coalesce(v_request->>'start_date',v_request->>'attendance_date',v_request->>'request_date',v_request->>'date'),
    'end_date',v_request->>'end_date',
    'leave_type',v_request->>'leave_type',
    'reason',left(coalesce(v_request->>'reason',''),500),
    'days',v_days,'balance_days',v_balance
  );
END;
$$;

