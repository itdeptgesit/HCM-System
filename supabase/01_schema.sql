declare t text;
begin
  foreach t in array array['companies','departments','office_locations','company_holidays','attendance_schedules','attendance_settings','leave_quotas','attendance_request_settings'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('drop policy if exists workforce_read on public.%I',t);
    execute format('create policy workforce_read on public.%I for select to authenticated using(public.current_account_id() is not null)',t);
    execute format('drop policy if exists workforce_hr_write on public.%I',t);
    execute format('create policy workforce_hr_write on public.%I for all to authenticated using(public.is_hr_admin()) with check(public.is_hr_admin())',t);
  end loop;
  foreach t in array array['attendance_records','leave_requests','overtime_requests','reimbursements','attendance_correction_requests','attendance_requests'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('drop policy if exists workforce_employee_read on public.%I',t);
    execute format('create policy workforce_employee_read on public.%I for select to authenticated using(user_id=public.current_account_id() or public.is_hr_admin() or exists(select 1 from public.user_accounts u where u.id::text=user_id and public.current_account_id()=any(array[u.supervisor_id::text,u.manager_id::text,u.vp_id::text,u.attendance_supervisor_id::text,u.attendance_hr_id::text,u.attendance_manager_id::text,u.attendance_vp_id::text])))',t);
  end loop;
  foreach t in array array['leave_requests','overtime_requests','reimbursements'] loop
    execute format('drop policy if exists workforce_employee_submit on public.%I',t);
    execute format('create policy workforce_employee_submit on public.%I for insert to authenticated with check(user_id=public.current_account_id() and status=''pending'')',t);
  end loop;
  foreach t in array array['leave_balance_periods','employee_transfer_history','user_activity_logs'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('drop policy if exists workforce_hr_manage on public.%I',t);
    execute format('create policy workforce_hr_manage on public.%I for all to authenticated using(public.is_hr_admin()) with check(public.is_hr_admin())',t);
  end loop;
end;
