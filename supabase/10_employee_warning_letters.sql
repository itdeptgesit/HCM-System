-- ==============================================================================
-- GESIT HCM SYSTEM: MIGRATION 10 - EMPLOYEE WARNING LETTERS (CATATAN SP KARYAWAN)
-- ==============================================================================
-- Tabel ini mengelola rekaman Surat Peringatan (Teguran Lisan/Tertulis, SP 1, SP 2, SP 3)
-- untuk manajemen sanksi kedisiplinan karyawan, masa berlaku (default 6 bulan),
-- dan riwayat pembinaan di The Gesit Companies.
-- ==============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.employee_warning_letters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  letter_number TEXT NOT NULL UNIQUE,
  employee_id BIGINT REFERENCES public.user_accounts(id) ON DELETE CASCADE,
  employee_code TEXT NOT NULL,
  employee_name TEXT NOT NULL,
  company TEXT,
  department TEXT,
  job_title TEXT,
  sp_level TEXT NOT NULL, -- 'Surat Teguran', 'SP 1', 'SP 2', 'SP 3'
  violation_category TEXT NOT NULL, -- 'Kedisiplinan & Presensi', 'Kinerja & Target', 'Pelanggaran SOP & Tata Tertib', 'Kode Etik & Integritas', 'Kelalaian Fasilitas / Finansial', 'Kerahasiaan Data & Informasi', 'Lainnya'
  incident_date DATE NOT NULL,
  issued_date DATE NOT NULL DEFAULT CURRENT_DATE,
  valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
  valid_until DATE NOT NULL, -- Umumnya 6 bulan sesuai regulasi ketenagakerjaan
  chronology TEXT NOT NULL,
  consequences TEXT,
  issuer_name TEXT DEFAULT 'HR Manager',
  issuer_title TEXT DEFAULT 'HR Manager',
  witness_name TEXT,
  status TEXT NOT NULL DEFAULT 'Aktif', -- 'Aktif', 'Selesai', 'Dibatalkan'
  revocation_reason TEXT,
  revoked_at TIMESTAMPTZ,
  revoked_by TEXT,
  attachment_url TEXT,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes untuk pencarian dan pemfilteran cepat
CREATE INDEX IF NOT EXISTS idx_warning_letters_emp_id ON public.employee_warning_letters(employee_id);
CREATE INDEX IF NOT EXISTS idx_warning_letters_emp_code ON public.employee_warning_letters(employee_code);
CREATE INDEX IF NOT EXISTS idx_warning_letters_status ON public.employee_warning_letters(status);
CREATE INDEX IF NOT EXISTS idx_warning_letters_sp_level ON public.employee_warning_letters(sp_level);
CREATE INDEX IF NOT EXISTS idx_warning_letters_valid_until ON public.employee_warning_letters(valid_until);
CREATE INDEX IF NOT EXISTS idx_warning_letters_company ON public.employee_warning_letters(company);

-- Trigger auto-update timestamp
CREATE OR REPLACE FUNCTION public.update_warning_letters_timestamp()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_warning_letters_updated_at ON public.employee_warning_letters;
CREATE TRIGGER trg_warning_letters_updated_at
BEFORE UPDATE ON public.employee_warning_letters
FOR EACH ROW
EXECUTE FUNCTION public.update_warning_letters_timestamp();

-- Enable Row Level Security (RLS)
ALTER TABLE public.employee_warning_letters ENABLE ROW LEVEL SECURITY;

-- Kebijakan RLS: Akses penuh untuk anon, authenticated, dan service_role
DROP POLICY IF EXISTS "Allow all access on employee_warning_letters" ON public.employee_warning_letters;
CREATE POLICY "Allow all access on employee_warning_letters"
ON public.employee_warning_letters
FOR ALL
TO PUBLIC
USING (true)
WITH CHECK (true);

-- Hak Akses Tabel
GRANT ALL ON TABLE public.employee_warning_letters TO anon, authenticated, service_role;
GRANT ALL ON SEQUENCE public.employee_warning_letters_id_seq TO anon, authenticated, service_role;

-- Reload cache schema PostgREST
NOTIFY pgrst, 'reload schema';

COMMIT;
