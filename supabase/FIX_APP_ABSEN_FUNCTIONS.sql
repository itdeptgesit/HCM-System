-- 8. Fungsi submit_attendance_correction_request (Koreksi Absen)
CREATE OR REPLACE FUNCTION public.submit_attendance_correction_request(
  p_attendance_date date, p_clock_in timestamptz, p_clock_out timestamptz, p_reason text
) RETURNS public.attendance_correction_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_user text := public.current_account_id();
  v_row public.attendance_correction_requests;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'USER_ACCOUNT_NOT_FOUND'; END IF;
  IF p_attendance_date IS NULL OR NULLIF(trim(p_reason),'') IS NULL THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
  INSERT INTO public.attendance_correction_requests(user_id, attendance_date, clock_in_time, clock_out_time, reason, status)
    VALUES(v_user, p_attendance_date, p_clock_in, p_clock_out, trim(p_reason), 'pending')
    ON CONFLICT (user_id, attendance_date) DO UPDATE
      SET clock_in_time = excluded.clock_in_time, clock_out_time = excluded.clock_out_time, reason = excluded.reason, status = 'pending', requested_at = now()
    RETURNING * INTO v_row;
  RETURN v_row;
END; $$;
GRANT EXECUTE ON FUNCTION public.submit_attendance_correction_request(date, timestamptz, timestamptz, text) TO authenticated, anon;

-- 9. Fungsi submit_outside_radius_attendance (Absen Luar Radius)
CREATE OR REPLACE FUNCTION public.submit_outside_radius_attendance(
  p_date date, p_lat double precision, p_lng double precision, p_reason text, p_photo_url text default null
) RETURNS public.attendance_requests LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_user text := public.current_account_id();
  v_row public.attendance_requests;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'USER_ACCOUNT_NOT_FOUND'; END IF;
  INSERT INTO public.attendance_requests(user_id, request_date, latitude, longitude, reason, photo_url, status)
    VALUES(v_user, p_date, p_lat, p_lng, trim(p_reason), p_photo_url, 'pending')
    ON CONFLICT (user_id, request_date) DO UPDATE
      SET latitude = excluded.latitude, longitude = excluded.longitude, reason = excluded.reason, photo_url = excluded.photo_url, status = 'pending', requested_at = now()
    RETURNING * INTO v_row;
  RETURN v_row;
END; $$;
GRANT EXECUTE ON FUNCTION public.submit_outside_radius_attendance(date, double precision, double precision, text, text) TO authenticated, anon;

-- 10. Fungsi update_my_avatar (Upload Foto Profil)
CREATE OR REPLACE FUNCTION public.update_my_avatar(p_avatar_url text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_user text := public.current_account_id();
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'USER_ACCOUNT_NOT_FOUND'; END IF;
  UPDATE public.user_accounts SET avatar_url = p_avatar_url, updated_at = now() WHERE id::text = v_user;
  RETURN p_avatar_url;
END; $$;
